"""Read / write CoD XANIM_EXPORT (version 3) text files.
A frame is a list of (offset, R) per part; R rows are the part's X/Y/Z axes in model space."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import paths
import re, glob, os
import numpy as np

SRC = os.path.join(paths.WAW, 'xanim_export')
NUM = r'(-?[\d.]+(?:e-?\d+)?)'


def find(name):
    return glob.glob(os.path.join(SRC, '**', name + '.XANIM_EXPORT'), recursive=True)[0]


def read(path):
    t = open(path, errors='replace').read().replace('\r', '')
    parts = re.findall(r'PART \d+ "([^"]+)"', t)
    fps = int(re.search(r'FRAMERATE (\d+)', t).group(1))
    frames = []
    for blk in re.split(r'\nFRAME (?=\d)', t.split('NOTETRACKS')[0])[1:]:
        ps = []
        for pb in re.split(r'\nPART ', blk)[1:]:
            v = {k: np.array([float(a), float(b), float(c)])
                 for k, a, b, c in re.findall(r'(OFFSET|X|Y|Z) %s %s %s' % (NUM, NUM, NUM), pb)}
            ps.append((v['OFFSET'], np.array([v['X'], v['Y'], v['Z']])))
        frames.append(ps)
    return {'parts': parts, 'fps': fps, 'frames': frames}


def write(path, anim, comment='generated by waw-clone-wars'):
    o = ['// %s' % comment, '', 'ANIMATION', 'VERSION 3', '', 'NUMPARTS %d' % len(anim['parts'])]
    o += ['PART %d "%s"' % (i, p) for i, p in enumerate(anim['parts'])]
    o += ['', 'FRAMERATE %d' % anim['fps'], 'NUMFRAMES %d' % len(anim['frames']), '']
    for fi, ps in enumerate(anim['frames']):
        o.append('FRAME %d' % fi)
        for pi, (off, R) in enumerate(ps):
            o.append('PART %d' % pi)
            o.append('OFFSET %.4f %.4f %.4f' % tuple(off))
            o.append('SCALE 1 1 1')
            for ax, row in zip('XYZ', R):
                o.append('%s %.4f %.4f %.4f' % (ax, row[0], row[1], row[2]))
            o.append('')
    o += ['NOTETRACKS', ''] + sum((['PART %d' % i, 'NUMTRACKS 0', ''] for i in range(len(anim['parts']))), [])
    with open(path, 'w', newline='\r\n') as f:
        f.write('\n'.join(o) + '\n')


def index(anim):
    return {p.lower(): i for i, p in enumerate(anim['parts'])}


def rigid(frame, R, pivot, t=(0, 0, 0), only=None):
    """Apply a rigid motion (rotate R about pivot, then translate t) to the parts in `only` (indices) or all."""
    out = []
    for i, (off, M) in enumerate(frame):
        if only is None or i in only:
            out.append((R @ (off - pivot) + pivot + np.array(t), M @ R.T))
        else:
            out.append((off, M))
    return out


