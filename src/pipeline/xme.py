"""Read and write Call of Duty XMODEL_EXPORT (version 6) text files."""
import numpy as np


def read(path):
    """Returns dict: bones [{name,parent,offset,rot(3x3 rows X,Y,Z)}], verts [(pos, [(bone,w)])],
    faces [(obj, mat, [(vert, normal, uv)]*3)], objects [names], materials [(name, type, image)]."""
    bones, verts, faces, objects, materials = [], [], [], [], []
    lines = open(path, errors='replace').read().replace('\r', '').replace(',', ' ').split('\n')
    i, n = 0, len(lines)
    section = 'bones'
    cur_bone = None
    cur_vert = None
    cur_face = None
    while i < n:
        t = lines[i].split()
        i += 1
        if not t:
            continue
        k = t[0]
        if k == 'NUMVERTS':
            section = 'verts'
        elif k == 'NUMFACES':
            section = 'faces'
        elif k == 'NUMOBJECTS':
            section = 'objects'
        elif k == 'NUMMATERIALS':
            section = 'materials'
        elif section == 'bones':
            if k == 'BONE' and len(t) >= 4:
                bones.append({'name': t[3].strip('"'), 'parent': int(t[2]), 'offset': None, 'rot': np.eye(3)})
            elif k == 'BONE':
                cur_bone = bones[int(t[1])]
            elif k == 'OFFSET':
                cur_bone['offset'] = np.array([float(x) for x in t[1:4]])
            elif k in 'XYZ' and len(k) == 1:
                cur_bone['rot'][{'X': 0, 'Y': 1, 'Z': 2}[k]] = [float(x) for x in t[1:4]]
        elif section == 'verts':
            if k == 'VERT':
                cur_vert = [None, []]
                verts.append(cur_vert)
            elif k == 'OFFSET':
                cur_vert[0] = np.array([float(x) for x in t[1:4]])
            elif k == 'BONE':
                cur_vert[1].append((int(t[1]), float(t[2])))
        elif section == 'faces':
            if k == 'TRI':
                cur_face = (int(t[1]), int(t[2]), [])
                faces.append(cur_face)
            elif k == 'VERT':
                cur_face[2].append([int(t[1]), None, None])
            elif k == 'NORMAL':
                cur_face[2][-1][1] = np.array([float(x) for x in t[1:4]])
            elif k == 'UV':
                cur_face[2][-1][2] = (float(t[2]), float(t[3]))
        elif section == 'objects':
            if k == 'OBJECT':
                objects.append(lines[i - 1].split('"')[1])
        elif section == 'materials':
            if k == 'MATERIAL':
                q = lines[i - 1].split('"')
                materials.append((q[1], q[3], q[5]))
    return {'bones': bones, 'verts': verts, 'faces': faces, 'objects': objects, 'materials': materials}


MATERIAL_TAIL = """COLOR 0.000000 0.000000 0.000000 1.000000
TRANSPARENCY 0.000000 0.000000 0.000000 1.000000
AMBIENTCOLOR 0.000000 0.000000 0.000000 1.000000
INCANDESCENCE 0.000000 0.000000 0.000000 1.000000
COEFFS 0.800000 0.000000
GLOW 0.000000 0
REFRACTIVE 6 1.000000
SPECULARCOLOR -1.000000 -1.000000 -1.000000 1.000000
REFLECTIVECOLOR -1.000000 -1.000000 -1.000000 1.000000
REFLECTIVE -1 -1.000000
BLINN -1.000000 -1.000000
PHONG -1.000000
"""


def write(path, model, comment='generated by waw-clone-wars'):
    """model uses the same structure read() returns."""
    o = ['// %s' % comment, 'MODEL', 'VERSION 6', '']
    b = model['bones']
    o.append('NUMBONES %d' % len(b))
    for i, x in enumerate(b):
        o.append('BONE %d %d "%s"' % (i, x['parent'], x['name']))
    o.append('')
    for i, x in enumerate(b):
        o.append('BONE %d' % i)
        o.append('OFFSET %f, %f, %f' % tuple(x['offset']))
        o.append('SCALE 1.000000, 1.000000, 1.000000')
        for ax, row in zip('XYZ', x['rot']):
            o.append('%s %f, %f, %f' % (ax, row[0], row[1], row[2]))
        o.append('')
    o.append('NUMVERTS %d' % len(model['verts']))
    for i, (pos, wts) in enumerate(model['verts']):
        o.append('VERT %d' % i)
        o.append('OFFSET %f, %f, %f' % tuple(pos))
        o.append('BONES %d' % len(wts))
        for bi, w in wts:
            o.append('BONE %d %f' % (bi, w))
        o.append('')
    o.append('NUMFACES %d' % len(model['faces']))
    for obj, mat, corners in model['faces']:
        o.append('TRI %d %d 0 0' % (obj, mat))
        for vi, nrm, uv in corners:
            o.append('VERT %d' % vi)
            o.append('NORMAL %f %f %f' % tuple(nrm))
            o.append('COLOR 1.000000 1.000000 1.000000 1.000000')
            o.append('UV 1 %f %f' % tuple(uv))
    o.append('')
    o.append('NUMOBJECTS %d' % len(model['objects']))
    for i, name in enumerate(model['objects']):
        o.append('OBJECT %d "%s"' % (i, name))
    o.append('')
    o.append('NUMMATERIALS %d' % len(model['materials']))
    for i, (name, typ, img) in enumerate(model['materials']):
        o.append('MATERIAL %d "%s" "%s" "%s"' % (i, name, typ, img))
        o.append(MATERIAL_TAIL.rstrip('\n'))
    with open(path, 'w', newline='\r\n') as f:
        f.write('\n'.join(o) + '\n')


def winding_agreement(model, sample=2000):
    """Fraction of faces whose geometric normal (v0,v1,v2 counter-clockwise) agrees with the stored normals."""
    agree = tot = 0
    for obj, mat, c in model['faces'][:sample]:
        p = [model['verts'][x[0]][0] for x in c]
        g = np.cross(p[1] - p[0], p[2] - p[0])
        nrm = c[0][1] + c[1][1] + c[2][1]
        if np.linalg.norm(g) < 1e-9:
            continue
        tot += 1
        agree += float(np.dot(g, nrm) > 0)
    return agree / max(tot, 1)


